"""Render the Homebrew cask and Scoop manifest for a release from its checksums.

    python scripts/package_managers.py 1.2.0 checksums.txt manifests/

The release workflow pushes the results to the tap and bucket repositories.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

DESCRIPTION = "Preview and copy the structure of a Discord server."
DEFAULT_REPOSITORY = "kaanxsrd/CloneX"
LICENSE = "GPL-3.0-only"


def parse_checksums(text: str) -> dict[str, str]:
    """Map file names to hashes from ``sha256sum`` output."""
    pairs = (line.split(maxsplit=1) for line in text.splitlines() if line.strip())
    return {name.strip().lstrip("*"): digest for digest, name in pairs}


def _digest(sums: dict[str, str], version: str, system: str, arch: str, suffix: str) -> str:
    return sums[f"clonex_{version}_{system}_{arch}.{suffix}"]


def homebrew_cask(version: str, sums: dict[str, str], repository: str) -> str:
    base = f"https://github.com/{repository}/releases/download/v#{{version}}"

    def stanza(system: str, arch: str, indent: str) -> str:
        digest = _digest(sums, version, system, arch, "tar.gz")
        url = f"{base}/clonex_#{{version}}_{system}_{arch}.tar.gz"
        return f'{indent}sha256 "{digest}"\n{indent}url "{url}"\n'

    return (
        "# Generated by scripts/package_managers.py in the CloneX repository. Do not edit.\n"
        'cask "clonex" do\n'
        f'  version "{version}"\n\n'
        "  on_macos do\n"
        f"    on_arm do\n{stanza('darwin', 'arm64', '      ')}    end\n"
        f"    on_intel do\n{stanza('darwin', 'amd64', '      ')}    end\n"
        "  end\n"
        "  on_linux do\n"
        f"    on_arm do\n{stanza('linux', 'arm64', '      ')}    end\n"
        f"    on_intel do\n{stanza('linux', 'amd64', '      ')}    end\n"
        "  end\n\n"
        '  name "clonex"\n'
        f'  desc "{DESCRIPTION}"\n'
        f'  homepage "https://github.com/{repository}"\n\n'
        "  livecheck do\n"
        '    skip "Auto-generated on release."\n'
        "  end\n\n"
        '  binary "clonex"\n\n'
        # The binary is not notarized: clear the quarantine flag Gatekeeper checks.
        "  postflight do\n"
        "    if OS.mac?\n"
        '      system_command "/usr/bin/xattr",\n'
        '                     args: ["-dr", "com.apple.quarantine", "#{staged_path}/clonex"]\n'
        "    end\n"
        "  end\n"
        "end\n"
    )


def scoop_manifest(version: str, sums: dict[str, str], repository: str) -> str:
    base = f"https://github.com/{repository}/releases/download/v{version}"

    def architecture(arch: str) -> dict[str, object]:
        name = f"clonex_{version}_windows_{arch}.zip"
        return {"url": f"{base}/{name}", "bin": ["clonex.exe"], "hash": sums[name]}

    manifest = {
        "version": version,
        "architecture": {"64bit": architecture("amd64"), "arm64": architecture("arm64")},
        "homepage": f"https://github.com/{repository}",
        "license": LICENSE,
        "description": DESCRIPTION,
    }
    return json.dumps(manifest, indent=4) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    version, checksums, output = argv
    sums = parse_checksums(Path(checksums).read_text(encoding="utf-8"))
    repository = os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPOSITORY)
    folder = Path(output)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "clonex.rb").write_text(
        homebrew_cask(version, sums, repository), encoding="utf-8", newline="\n"
    )
    (folder / "clonex.json").write_text(
        scoop_manifest(version, sums, repository), encoding="utf-8", newline="\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
